-- 외래키 제약조건 먼저 삭제 (테이블 드롭)
DROP TABLE IF EXISTS `CHICKEN_INOCULATION_HISTORY`;
DROP TABLE IF EXISTS `chicken_weight_history`;
DROP TABLE IF EXISTS `CHICKEN`;
DROP TABLE IF EXISTS `DANGER_NOTICE`;
DROP TABLE IF EXISTS `CHICKEN_BATCH`;
DROP TABLE IF EXISTS `FARM_MANAGEMENT`;
DROP TABLE IF EXISTS `FARM_STATUS`;
DROP TABLE IF EXISTS `NOTE`;
DROP TABLE IF EXISTS `MEMBER`;
DROP TABLE IF EXISTS `CHICKEN_FARM`;

-- 기본 테이블 생성
CREATE TABLE `CHICKEN_FARM` (
	`FARM_NUM` INT PRIMARY KEY AUTO_INCREMENT NOT NULL COMMENT '축사 아이디',
	`FARM_NAME` VARCHAR(20) NOT NULL COMMENT '축사 이름'
);

CREATE TABLE `FARM_STATUS` (
	`FARM_STATUS_NUM` INT AUTO_INCREMENT NOT NULL COMMENT '축사 상태 아이디',
	`NO2_DATA` FLOAT NOT NULL DEFAULT 0 COMMENT '이산화질소',
	`TEMP_DATA` FLOAT NOT NULL DEFAULT 0 COMMENT '온도',
	`HUM_DATA` FLOAT NOT NULL DEFAULT 0 COMMENT '습도',
	`LUX_DATA` FLOAT NOT NULL DEFAULT 0 COMMENT '조명',
	`CO_DATA` FLOAT NOT NULL DEFAULT 0 COMMENT '일산화탄소',
	`CO2_DATA` FLOAT NOT NULL DEFAULT 0 COMMENT '이산화탄소',
	`NH3_DATA` FLOAT NOT NULL DEFAULT 0 COMMENT '암모니아',
	`REC_TIME` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '기록시간',
	`FARM_ID` INT NOT NULL COMMENT '축사 아이디',
	PRIMARY KEY (`FARM_STATUS_NUM`),
	FOREIGN KEY (`FARM_ID`) REFERENCES `CHICKEN_FARM`(`FARM_NUM`)
);

CREATE TABLE `FARM_MANAGEMENT` (
	`MANAGEMENT_NUM` INT AUTO_INCREMENT NOT NULL COMMENT '관리 번호',
	`FEED_CONSUMPTION_G` FLOAT NOT NULL DEFAULT 0 COMMENT '전체 모이 소비량',
	`WATER_CONSUMPTION_ML` FLOAT NOT NULL DEFAULT 0 COMMENT '전체 물 소비량',
	`REC_TIME` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '기록 시간',
	`FARM_NUM` INT NOT NULL COMMENT '축사 아이디',
	PRIMARY KEY (`MANAGEMENT_NUM`),
	FOREIGN KEY (`FARM_NUM`) REFERENCES `CHICKEN_FARM`(`FARM_NUM`)
);

