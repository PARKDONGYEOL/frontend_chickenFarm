-- 환경 설정 테이블 생성
CREATE TABLE IF NOT EXISTS `ENV_SETTINGS` (
    `ID` INT PRIMARY KEY DEFAULT 1,
    `LED_THRESHOLD` DOUBLE NOT NULL DEFAULT 300 COMMENT 'LED 조명 기준 (lux)',
    `DOOR_OPEN_TEMP` DOUBLE NOT NULL DEFAULT 25 COMMENT '문 열기 온도 (°C)',
    `DOOR_CLOSE_TEMP` DOUBLE NOT NULL DEFAULT 15 COMMENT '문 닫기 온도 (°C)',
    `FAN_HUMIDITY_THRESHOLD` DOUBLE NOT NULL DEFAULT 75 COMMENT '팬 가동 습도 기준 (%)',
    `FAN_CO2_THRESHOLD` DOUBLE NOT NULL DEFAULT 1000 COMMENT '팬 가동 CO2 기준 (ppm)',
    `FAN_CO_THRESHOLD` DOUBLE NOT NULL DEFAULT 30 COMMENT '팬 가동 CO 기준 (ppm)',
    `FAN_SPEED` DOUBLE NOT NULL DEFAULT 60 COMMENT '팬 속도 (%)',
    `TEMP_HIGH_ALERT` DOUBLE NOT NULL DEFAULT 35 COMMENT '고온 알림 기준 (°C)',
    `TEMP_LOW_ALERT` DOUBLE NOT NULL DEFAULT 10 COMMENT '저온 알림 기준 (°C)',
    `HUMIDITY_HIGH_ALERT` DOUBLE NOT NULL DEFAULT 85 COMMENT '고습도 알림 기준 (%)',
    `HUMIDITY_LOW_ALERT` DOUBLE NOT NULL DEFAULT 30 COMMENT '저습도 알림 기준 (%)',
    `CO2_ALERT` DOUBLE NOT NULL DEFAULT 2000 COMMENT 'CO2 알림 기준 (ppm)',
    `CO_ALERT` DOUBLE NOT NULL DEFAULT 50 COMMENT 'CO 알림 기준 (ppm)',
    `NH3_ALERT` DOUBLE NOT NULL DEFAULT 25 COMMENT 'NH3 알림 기준 (ppm)',
    `ENV_STATUS_GOOD` DOUBLE NOT NULL DEFAULT 80 COMMENT '환경 상태 양호 기준 (점)',
    `ENV_STATUS_FAIR` DOUBLE NOT NULL DEFAULT 60 COMMENT '환경 상태 좋음 기준 (점)',
    `CREATED_AT` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '생성일시',
    `UPDATED_AT` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '수정일시'
);

